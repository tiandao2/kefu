#!/usr/bin/python3
"""Validate and atomically refresh the Nginx mainland allowlist."""
import argparse
import datetime
import fcntl
import hashlib
import ipaddress
import json
import os
from pathlib import Path
import subprocess
import urllib.request

SOURCES = {
    4: "https://raw.githubusercontent.com/gaoyifan/china-operator-ip/ip-lists/china.txt",
    6: "https://raw.githubusercontent.com/gaoyifan/china-operator-ip/ip-lists/china6.txt",
}
TARGET = Path("/etc/nginx/geo/kf-mainland.cidrs")


def download():
    networks = []
    records = []
    for version, url in SOURCES.items():
        with urllib.request.urlopen(url, timeout=30) as response:
            raw = response.read(5_000_001)
        if len(raw) > 5_000_000:
            raise ValueError("Unexpectedly large range list")
        entries = [ipaddress.ip_network(line.strip()) for line in raw.decode().splitlines() if line.strip()]
        minimum = 1000 if version == 4 else 100
        if not minimum <= len(entries) <= 100_000:
            raise ValueError("Unexpected range count")
        for network in entries:
            if network.version != version or network.prefixlen < (8 if version == 4 else 16):
                raise ValueError("Invalid address family or excessively broad range")
            if not network.network_address.is_global:
                raise ValueError("Non-public range in downloaded list")
        networks.extend(entries)
        records.append({"url": url, "networks": len(entries), "sha256": hashlib.sha256(raw).hexdigest()})
    def includes(value):
        address = ipaddress.ip_address(value)
        return any(address.version == n.version and address in n for n in networks)
    for value in ["223.5.5.5", "114.114.114.114", "119.29.29.29", "2400:3200::1"]:
        if not includes(value):
            raise ValueError("Expected mainland reference address missing: " + value)
    for value in ["8.8.8.8", "1.1.1.1", "43.129.28.176", "168.95.1.1", "202.175.1.1", "2606:4700:4700::1111"]:
        if includes(value):
            raise ValueError("Unexpected overseas reference address included: " + value)
    networks = sorted(set(networks), key=lambda n: (n.version, int(n.network_address), n.prefixlen))
    text = "# Generated by kf-mainland-update; unknown addresses are denied.\n"
    text += "".join(f"{network} 1;\n" for network in networks)
    return text.encode(), records


def atomic_write(path, contents):
    temporary = path.with_name(path.name + ".new")
    temporary.write_bytes(contents)
    temporary.chmod(0o644)
    os.replace(temporary, path)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--prepare", action="store_true", help="Create data before initial Nginx configuration installation")
    args = parser.parse_args()
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    with Path("/run/kf-mainland-update.lock").open("w") as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        contents, sources = download()
        previous = TARGET.read_bytes() if TARGET.exists() else None
        atomic_write(TARGET, contents)
        if not args.prepare:
            try:
                subprocess.run(["nginx", "-t"], check=True)
                subprocess.run(["systemctl", "reload", "nginx"], check=True)
            except Exception:
                if previous is not None:
                    atomic_write(TARGET, previous)
                    subprocess.run(["nginx", "-t"], check=True)
                    subprocess.run(["systemctl", "reload", "nginx"], check=True)
                else:
                    TARGET.unlink(missing_ok=True)
                raise
        metadata = {"updated_at_utc": datetime.datetime.now(datetime.timezone.utc).isoformat(), "sources": sources}
        atomic_write(TARGET.parent / "kf-mainland-update.json", (json.dumps(metadata, indent=2) + "\n").encode())
        print(json.dumps(metadata))


if __name__ == "__main__":
    main()
